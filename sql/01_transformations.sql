DROP VIEW IF EXISTS V_REGIONAL_TARGETS;
DROP VIEW IF EXISTS V_MONTHLY;
DROP VIEW IF EXISTS V_SALES_DETAIL;
CREATE VIEW V_SALES_DETAIL AS
SELECT o.*,p.PRODUCT_NAME,p.CATEGORY,c.SEGMENT,c.REGION,k.UNIT_COST,
ROUND(o.QUANTITY*o.SELLING_PRICE*(1-o.DISCOUNT),2) AS REVENUE,
ROUND(o.QUANTITY*k.UNIT_COST,2) AS COGS,
ROUND(o.QUANTITY*o.SELLING_PRICE*(1-o.DISCOUNT),2)-ROUND(o.QUANTITY*k.UNIT_COST,2) AS GROSS_PROFIT
FROM ORDERS o JOIN PRODUCTS p ON o.PRODUCT_ID=p.PRODUCT_ID
JOIN CUSTOMERS c ON o.CUSTOMER_ID=c.CUSTOMER_ID
JOIN COSTS k ON o.PRODUCT_ID=k.PRODUCT_ID AND o.MONTH=k.MONTH;
CREATE VIEW V_MONTHLY AS
SELECT MONTH,PRODUCT_ID,REGION,SUM(QUANTITY) QUANTITY,SUM(REVENUE) REVENUE,
SUM(COGS) COGS,SUM(GROSS_PROFIT) GROSS_PROFIT,COUNT(DISTINCT ORDER_ID) ORDER_COUNT
FROM V_SALES_DETAIL GROUP BY MONTH,PRODUCT_ID,REGION;
CREATE VIEW V_REGIONAL_TARGETS AS
SELECT t.MONTH,t.REGION,t.SALES_TARGET,t.MARGIN_TARGET,a.REVENUE,a.GROSS_PROFIT,
a.REVENUE-t.SALES_TARGET REVENUE_VARIANCE,
a.GROSS_PROFIT/NULLIF(a.REVENUE,0) MARGIN_PCT
FROM TARGETS t LEFT JOIN
(SELECT MONTH,REGION,SUM(REVENUE) REVENUE,SUM(GROSS_PROFIT) GROSS_PROFIT FROM V_MONTHLY GROUP BY MONTH,REGION) a
ON t.MONTH=a.MONTH AND t.REGION=a.REGION;
