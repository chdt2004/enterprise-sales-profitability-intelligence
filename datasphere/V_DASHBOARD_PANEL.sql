SELECT m."MONTH", m."PRODUCT_ID", p."PRODUCT_NAME", p."CATEGORY", m."REGION", m."QUANTITY", m."REVENUE", m."COGS", m."GROSS_PROFIT", m."ORDER_COUNT", f."PHASE", f."MODEL", f."FORECAST_QUANTITY", f."ACTUAL_QUANTITY"
FROM "V_MONTHLY" m JOIN "PRODUCTS" p ON m."PRODUCT_ID"=p."PRODUCT_ID"
LEFT JOIN "FORECAST" f ON m."MONTH"=f."MONTH" AND m."PRODUCT_ID"=f."PRODUCT_ID" AND m."REGION"=f."REGION"
UNION ALL
SELECT f."MONTH", f."PRODUCT_ID", p."PRODUCT_NAME", p."CATEGORY", f."REGION", NULL, NULL, NULL, NULL, NULL, f."PHASE", f."MODEL", f."FORECAST_QUANTITY", f."ACTUAL_QUANTITY"
FROM "FORECAST" f JOIN "PRODUCTS" p ON f."PRODUCT_ID"=p."PRODUCT_ID" WHERE f."PHASE"='Future' 
